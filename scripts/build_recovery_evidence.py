"""Freeze and plot the saved October recovery diagnosis for both manuscripts."""

import argparse
import hashlib
import json
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--diagnosis", type=Path, required=True)
    parser.add_argument("--development-analysis", type=Path)
    args = parser.parse_args()
    raw = args.diagnosis.read_bytes()
    counts = json.loads(raw)["summary"]
    stages = counts["sample_stages"]
    frames = counts["frame_stages"]
    assert sum(stages.values()) == counts["attempts"]
    assert sum(frames.values()) == counts["complete_frames"]
    n, k, z = counts["attempts"], stages["exact_recovery"], 1.959963984540054
    p = k / n
    center = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    values = {
        "OctAttempts": n, "OctExact": k,
        "OctGenerationFailures": stages["generation_failure"],
        "OctReceiverFailures": stages["receiver_failure"],
        "OctComplete": n - stages["generation_failure"],
        "OctFrames": counts["complete_frames"],
        "OctCorrectFrames": frames["correct_selection"],
        "OctConfusedFrames": frames["classification_confusion"],
        "OctIdenticalPromptConfusions": counts["identical_prompt_disagreement_frames"],
        "OctWilsonLow": f"{100 * (center - half):.1f}",
        "OctWilsonHigh": f"{100 * (center + half):.1f}",
    }
    data = ROOT / "common" / "data"
    data.mkdir(exist_ok=True)
    snapshot = {"artifact": "oppression25_fresh_20261003T113428Z", "diagnosis_sha256": hashlib.sha256(raw).hexdigest(), "counts": counts, "values": values}
    (data / "october_recovery_evidence.json").write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
    (data / "october_recovery_values.tex").write_text("% Generated by scripts/build_recovery_evidence.py.\n" + "".join(f"\\newcommand{{\\{key}}}{{{value}}}\n" for key, value in values.items()), encoding="utf-8")
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.5), constrained_layout=True)
    panels = [(axes[0], ["Exact\nrecovery", "Generation\nfailure", "Receiver\nfailure"], [k, stages["generation_failure"], stages["receiver_failure"]], f"All {n} assigned messages"), (axes[1], ["Correct\nselection", "Confused\nselection"], [frames["correct_selection"], frames["classification_confusion"]], f"{counts['complete_frames']} carriers in complete sequences")]
    for ax, labels, heights, title in panels:
        bars = ax.bar(labels, heights, color=["#247c65", "#be7734", "#ab4141"][:len(labels)])
        ax.bar_label(bars, padding=4)
        ax.set_title(title, fontsize=11)
        ax.set_ylabel("Count")
        ax.set_ylim(0, max(heights) * 1.2)
        ax.spines[["top", "right"]].set_visible(False)
    for suffix in ["pdf", "png"]:
        fig.savefig(ROOT / "common" / "figures" / f"october_recovery_stages.{suffix}", dpi=180)
    plt.close(fig)
    if args.development_analysis:
        freeze_development(args.development_analysis, data)


def freeze_development(path: Path, data: Path):
    raw = path.read_bytes()
    report = json.loads(raw)
    messages, costs = report["messages"], report["costs"]
    values = {
        "DevAttempted": len(messages), "DevExact": sum(m["exact"] for m in messages),
        "DevFailed": sum(not m["exact"] for m in messages), "DevUnattempted": report["unattempted"],
        "DevFrames": report["complete_frames"], "DevWrong": report["incorrect_selections"],
        "DevCalls": costs["calls"], "DevSenderCalls": costs["calls_by_stage"]["sender"],
        "DevReceiverCalls": costs["calls_by_stage"]["receiver"],
        "DevWords": sum(m["visible_words_saved_carriers"] for m in messages),
        "DevMinutes": f"{sum(m['elapsed_ms'] for m in messages) / 60000:.1f}",
    }
    snapshot = {"analysis_sha256": hashlib.sha256(raw).hexdigest(), "signature": report["signature"], "gate": report["gate"], "values": values, "costs": costs}
    (data / "luna_development_evidence.json").write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
    (data / "luna_development_values.tex").write_text("% Generated from stopped development run; not a fixed-size reliability estimate.\n" + "".join(f"\\newcommand{{\\{key}}}{{{value}}}\n" for key, value in values.items()), encoding="utf-8")


if __name__ == "__main__":
    main()
