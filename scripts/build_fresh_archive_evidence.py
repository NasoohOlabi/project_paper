"""Build the shared bilingual evidence snapshot from saved rounds 4--6."""
import hashlib
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
WORKSPACE = PAPER.parent
BASE = WORKSPACE / 'AstrasReview' / 'iterations'
provenance = {}

def read(path):
    raw = path.read_bytes()
    provenance[str(path.relative_to(WORKSPACE))] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)

values = {}
r4 = read(BASE / 'round-4/live_analysis.json')
values['FreshAssigned'] = 6
values['FreshStorageBits'] = 64
for arm, name in [('anchored', 'Anchored'), ('wren_g5', 'Gfive')]:
    rows = [r for r in r4['rows'] if r['arm'] == arm]
    assert len(rows) == 6
    values['FreshFour' + name + 'Exact'] = sum(r['exact'] for r in rows)
read(BASE / 'round-4/live_manifest.json')
read(BASE / 'round-4/receiver_retry_supplement.json')
campaigns = {}
for number, prefix in [(5, 'FreshDev'), (6, 'FreshHeld')]:
    directory = BASE / f'round-{number}'
    analysis = read(directory / 'analysis.json')
    manifest = read(directory / 'manifest_private.json')
    quality = read(directory / 'quality_audit.json')
    read(directory / 'quality_preflight.json')
    read(directory / 'quality_judge_freeze.json')
    rows = [read(directory / 'runs' / f'{i:02d}' / 'result.json') for i in range(6)]
    for policy, suffix in [('baseline2', 'Two'), ('baseline7', 'Seven'), ('concise7', 'Concise')]:
        saved = analysis['policies'][policy]
        assert saved['exact'] == sum(r['policies'][policy]['exact'] for r in rows)
        assert saved['words_all'] == sum(r['policies'][policy]['words'] for r in rows)
        for field, label in [('exact', 'Exact'), ('words_all', 'Words'), ('emitted_frames', 'Frames')]:
            values[prefix + suffix + label] = saved[field]
        values[prefix + suffix + 'Calls'] = saved['generation_cost']['calls']
        values[prefix + suffix + 'ReceiverCalls'] = saved['receiver_cost']['calls']
        values[prefix + suffix + 'Bpw'] = f"{saved['bits_per_word_all_attempts']:.6f}"
    baseline, concise = analysis['policies']['baseline7'], analysis['policies']['concise7']
    values[prefix + 'Saving'] = f"{100 * (baseline['words_all'] - concise['words_all']) / baseline['words_all']:.2f}"
    categories = quality['pair_categories']
    for field, label in [('baseline7', 'BaselineWins'), ('concise7', 'ConciseWins'), ('tie', 'Ties'), ('discordant', 'Discordant'), ('invalid', 'InvalidPairs')]:
        values[prefix + label] = categories.get(field, 0)
    values[prefix + 'Pairs'] = quality['pairs']
    values[prefix + 'Orders'] = quality['tasks']
    values[prefix + 'QualityPosts'] = len({k.split('/')[0] for k in quality['pairs_by_source']})
    campaigns[str(number)] = {'policies': analysis['policies'], 'selected': manifest['selected'], 'quality': quality['pair_categories'], 'quality_usage': quality['usage']}

data = PAPER / 'common/data'
data.mkdir(exist_ok=True)
snapshot = {'scope': 'Local archive public-observation simulation, deterministic thread-only variant; development and untouched panels separate.', 'artifact_sha256': provenance, 'round4_primary': {'anchored': values['FreshFourAnchoredExact'], 'g5': values['FreshFourGfiveExact'], 'assigned_each': 6}, 'campaigns': campaigns, 'values': values}
(data / 'fresh_archive_evidence.json').write_text(json.dumps(snapshot, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
(data / 'fresh_archive_values.tex').write_text('% Generated by scripts/build_fresh_archive_evidence.py from SHA256-pinned saved artifacts.\n' + ''.join(f'\\newcommand{{\\{key}}}{{{value}}}\n' for key, value in values.items()), encoding='utf-8')
print(json.dumps(values, indent=2))
