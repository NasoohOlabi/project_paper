"""Record post-set overlap from saved manifests without changing source artifacts."""
import hashlib
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
WORKSPACE = PAPER.parent
BACKEND = WORKSPACE / 'stego-side-wing'
sources = {}

def read(path):
    raw = path.read_bytes()
    sources[str(path.relative_to(WORKSPACE))] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)

excerpt = read(BACKEND / 'metrics/e2e_runs/oppression25_fresh_20261003T113428Z/manifest.json')
development = read(BACKEND / 'metrics/recovery_development/luna10_20261003_v2/manifest.json')
pilot = read(BACKEND / 'metrics/benchmark/arctic_shift_recovery_pilot_20260926/locked/manifest.json')
prompt = read(BACKEND / 'metrics/experiments/wren/g0_g3/g0_g3_live_20260919/manifest.json')
archive = WORKSPACE / 'AstrasReview/iterations'
panels = {n: read(archive / f'round-{n}' / ('live_manifest.json' if n == 4 else 'manifest_private.json')) for n in (4, 5, 6)}
groups = {
    'source_excerpt': {row['post_id'] for row in excerpt['samples']},
    'independent_development': {row['post_id'] for row in development['samples']},
    'limited_carrier_pilot': set(pilot['post_ids'][:25]),
    'prompt_development': set(prompt['post_ids']),
    **{f'archive_{n}': {row['post_id'] for row in panel['selected']} for n, panel in panels.items()},
}
assert len(groups['source_excerpt']) == 25
assert len(groups['independent_development']) == 10
assert len(groups['prompt_development']) == 48
assert groups['archive_4'] == groups['archive_5']
assert not groups['archive_5'] & groups['archive_6']
overlaps = {f'{a}__{b}': sorted(groups[a] & groups[b]) for i, a in enumerate(groups) for b in list(groups)[i+1:]}
values = {
    'DsExcerptPosts': len(groups['source_excerpt']),
    'DsIndependentPosts': len(groups['independent_development']),
    'DsDevelopmentReused': len(groups['source_excerpt'] & groups['independent_development']),
    'DsDevelopmentAdditional': len(groups['independent_development'] - groups['source_excerpt']),
    'DsArchivePanelPosts': len(groups['archive_5']),
    'DsArchiveReused': len(groups['archive_4'] & groups['archive_5']),
    'DsArchivePanelOverlap': len(groups['archive_5'] & groups['archive_6']),
    'DsPromptPosts': len(groups['prompt_development']),
}
assert values['DsDevelopmentReused'] == 7 and values['DsDevelopmentAdditional'] == 3
out = PAPER / 'common/data'
(out / 'dataset_overlap_evidence.json').write_text(json.dumps({'source_sha256': sources, 'post_sets': {k: sorted(v) for k, v in groups.items()}, 'intersections': overlaps, 'values': values}, indent=2) + '\n', encoding='utf-8')
(out / 'dataset_overlap_values.tex').write_text('% Generated by scripts/build_dataset_overlap_evidence.py.\n' + ''.join(f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in values.items()), encoding='utf-8')
print(json.dumps(values))
